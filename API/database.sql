-- Internships Registration Table
CREATE TABLE IF NOT EXISTS `internships` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
    `internship_type` VARCHAR(100) NOT NULL,
    `gender` VARCHAR(20) NOT NULL,
    `name` VARCHAR(255) NOT NULL,
    `email` VARCHAR(255) NOT NULL,
    `phone` VARCHAR(50) NOT NULL,
    `college` VARCHAR(255) NOT NULL,
    `city` VARCHAR(100) NOT NULL,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Admin OTP Table
CREATE TABLE IF NOT EXISTS `admin_otp` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
    `email` VARCHAR(255) NOT NULL,
    `otp` VARCHAR(10) NOT NULL,
    `expires_at` DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Internship Courses & Tracks Table
CREATE TABLE IF NOT EXISTS `internship_courses` (
    `id` INT AUTO_INCREMENT PRIMARY KEY,
    `slug` VARCHAR(100) NOT NULL UNIQUE,
    `title` VARCHAR(255) NOT NULL,
    `duration_value` INT NOT NULL DEFAULT 1,
    `duration_unit` VARCHAR(20) NOT NULL DEFAULT 'Weeks',
    `duration` VARCHAR(100) NOT NULL,
    `mode` VARCHAR(50) NOT NULL DEFAULT 'On-site',
    `is_active` TINYINT(1) NOT NULL DEFAULT 1,
    `description` LONGTEXT DEFAULT NULL,
    `curriculum` LONGTEXT DEFAULT NULL,
    `sort_order` INT NOT NULL DEFAULT 0,
    `created_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    `updated_at` TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

